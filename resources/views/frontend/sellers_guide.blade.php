                {{-- SECTION 3: How to Price Your Home --}}
                <div id="pricing" class="sg-section">
                    <h2>3. How to Price Your Home for the BC Market</h2>
                    <p>Pricing is simultaneously the most impactful and most nuanced decision in the selling process. Overprice your home and it sits — accumulating days on market and signaling weakness to buyers. Underprice it and you leave money on the table. Correctly price it and you attract strong, competitive offers.</p>

                    <h3>The Comparable Sales (CMA) Method</h3>
                    <p>A Comparative Market Analysis (CMA) is the standard tool agents use to establish market value. It compares your property to recently sold homes that are similar in size, condition, age, location, and features. The most reliable comparables are sold in the last 30–90 days within your immediate neighbourhood. In fast-moving markets, comparables from 6 months ago may already be outdated.</p>

                    <p>Key factors that affect how your property compares to recent sales include:</p>
                    <ul>
                        <li><strong>Location within the neighbourhood</strong> — proximity to transit, schools, parks, and commercial noise all affect value</li>
                        <li><strong>Floor level and view</strong> — critical for condos; upper floors with views consistently command premiums</li>
                        <li><strong>Condition and updates</strong> — renovated kitchens and bathrooms add measurable value; deferred maintenance subtracts from it</li>
                        <li><strong>Outdoor space</strong> — in Greater Vancouver, private outdoor space (balcony, patio, yard) commands significant premiums post-2020</li>
                        <li><strong>Strata fees and age of building</strong> — for condos, high strata fees and an aging building with a significant depreciation report affect perceived value</li>
                        <li><strong>Parking and storage</strong> — in Vancouver, a parking stall can add $30,000–$70,000+ to a condo's value depending on the building and neighbourhood</li>
                    </ul>

                    <h3>Strategic Pricing in a Competitive Market</h3>
                    <p>In a seller's market, experienced agents sometimes recommend pricing just below market value to generate multiple offers and drive the final price above asking. This strategy requires a strong buyer network to execute — which is why agent platform reach matters. Without multiple qualified buyers aware of your listing on day one, this strategy can backfire.</p>

                    <h3>Adjusting Price After Listing</h3>
                    <p>If your home has not received an accepted offer within 2–3 weeks and showing traffic is low, a price adjustment is usually warranted. Each week on market makes a property look less desirable to buyers. A timely, meaningful price reduction (3–5%) typically reactivates buyer interest more effectively than a series of small reductions that signal desperation.</p>

