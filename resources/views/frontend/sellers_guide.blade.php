                <div id="market-conditions" class="sg-section">
                    <h2>5. How BC Market Conditions Affect Your Selling Strategy</h2>
                    <p>British Columbia's real estate market is not uniform. Vancouver proper, the North Shore, Burnaby, Richmond, Surrey, Langley, and the Fraser Valley each move independently — and within those cities, condos, townhouses, and single-family homes can be in entirely different market phases at the same time. Understanding your specific submarket is critical before choosing a pricing and timing strategy.</p>

                    <h3>Seller's Market: Low Inventory, High Demand</h3>
                    <p>In a seller's market, active listings are low relative to buyer demand. Homes sell quickly (often in under 2 weeks), frequently above asking price, with multiple competing offers. In this environment:</p>
                    <ul>
                        <li>Price at or just below market value to trigger multiple offers</li>
                        <li>Set a firm offer review date (e.g. "offers reviewed Tuesday at 7pm") to concentrate buyer competition</li>
                        <li>Be prepared for subjects-free offers — but never waive your right to consult your agent on each offer's terms</li>
                        <li>Short closing periods are common — ensure your plans for your next home are in place</li>
                    </ul>

                    <h3>Buyer's Market: High Inventory, Lower Demand</h3>
                    <p>In a buyer's market, there are more listings than active buyers. Homes take longer to sell and often sell below asking. In this environment:</p>
                    <ul>
                        <li>Pricing accuracy is critical — overpriced homes are completely ignored while correctly priced homes still sell</li>
                        <li>Presentation quality becomes a significant differentiator — staging, photography, and virtual tours matter more</li>
                        <li>Buyer's agent commission should be competitive — in a buyer's market, agents have many options and will prioritize well-compensated listings</li>
                        <li>Be prepared for longer timelines and buyer-friendly subject periods</li>
                        <li>The seller's negotiating position is weaker — have a realistic walk-away number in mind before listing</li>
                    </ul>

                    <h3>Balanced Market</h3>
                    <p>In a balanced market (roughly equal supply and demand), average days on market is typically 3–6 weeks and sold prices run 97–100% of list. Standard pricing strategy applies — price accurately based on recent comparables, present the property well, and be responsive to buyer feedback.</p>

