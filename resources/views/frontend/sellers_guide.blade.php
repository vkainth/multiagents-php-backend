                <div id="listing-process" class="sg-section">
                    <h2>4. What to Expect During the Listing Process</h2>
                    <p>From signing the listing agreement to receiving keys from the buyer, here is a clear timeline of what to expect.</p>

                    <h3>Phase 1: Pre-Listing Preparation (1–3 Weeks Before Listing)</h3>
                    <ul>
                        <li>Sign the listing agreement and confirm list price, commission, and marketing plan</li>
                        <li>Declutter, deep-clean, and stage the property (agent may provide guidance or staging consultation)</li>
                        <li>Professional photography and 3D Matterport virtual tour (typically scheduled 1–2 days before listing)</li>
                        <li>For strata properties: request updated strata documents (Form B, minutes, financial statements, depreciation report)</li>
                        <li>Complete the Property Disclosure Statement (PDS) — disclosure of known defects and issues</li>
                        <li>Confirm lockbox installation and showing instructions with your agent</li>
                    </ul>

                    <h3>Phase 2: Active on Market</h3>
                    <ul>
                        <li>Your listing goes live on MLS, agent website, and all marketing platforms simultaneously</li>
                        <li>Showings are coordinated by your agent — expect 24–48 hours notice (or less, in a hot market)</li>
                        <li>Your agent relays buyer feedback after each showing</li>
                        <li>Weekly updates on showing count, online views, and comparable sales</li>
                        <li>Offer presentation: your agent reviews each offer with you and advises on response strategy</li>
                    </ul>

                    <h3>Phase 3: Accepted Offer and Subject Period</h3>
                    <ul>
                        <li>Once an offer is accepted, the buyer typically has 7–14 business days to remove subjects (financing, inspection, strata document review)</li>
                        <li>Your agent communicates with the buyer's agent throughout the subject period</li>
                        <li>If subjects are removed in writing, the deal becomes firm — congratulations, your home is sold</li>
                        <li>If subjects are not removed, the deal falls through and your listing returns to market</li>
                    </ul>

                    <h3>Phase 4: Completion and Possession</h3>
                    <ul>
                        <li>Your notary or lawyer handles conveyancing (title transfer and fund exchange)</li>
                        <li>Completion date: legal ownership transfers and sale proceeds are deposited (usually 30–90 days after accepted offer)</li>
                        <li>Possession date: buyer takes physical possession (typically one day after completion)</li>
                        <li>Ensure utilities are cancelled or transferred and the property is in agreed-upon condition</li>
                    </ul>
