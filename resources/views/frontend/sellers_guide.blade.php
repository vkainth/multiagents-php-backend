                <div id="choose-agent" class="sg-section">
                    <h2>1. How to Choose a Listing Agent in BC</h2>
                    <p>Choosing the right listing agent is the single most consequential decision you'll make when selling your home. Your agent determines your pricing strategy, the quality of your marketing, your negotiating position, and how smoothly the transaction closes. Here is what to look for — and what to ask.</p>

                    <h3>Track Record and Local Expertise</h3>
                    <p>Ask any prospective agent for their list-to-sold price ratio and average days on market for properties they listed in your area over the past 12 months. A strong agent will have this data ready. Look for a ratio above 98% in a balanced market — and ask how that compares to the neighbourhood average. Local knowledge matters: an agent who regularly works in your submarket will price and position your home more accurately than one working unfamiliar territory.</p>

                    <h3>Buyer Network and Platform Reach</h3>
                    <p>Your listing needs to reach qualified buyers — not just sit on MLS. Ask each agent: "Beyond MLS, how will you market my property?" Top agents maintain large buyer databases, email lists, and high-traffic websites that expose your home to buyers who are actively searching. For context, the Hani &amp; Les | BC Condos And Homes platform reaches over 157,000 registered buyers and more than 300,000 monthly visitors — BC's largest realtor-owned buyer network. That kind of reach directly translates to more showings and stronger offers.</p>

                    <h3>Questions to Ask Every Agent You Interview</h3>
                    <ul>
                        <li>What is your list-to-sold price ratio for properties like mine in the past year?</li>
                        <li>What is your average days on market vs. the neighbourhood average?</li>
                        <li>How many active buyers do you have in your database for this price range and neighbourhood?</li>
                        <li>Who does your photography, staging, and virtual tour? Do you cover those costs?</li>
                        <li>How often will you update me after listing — and what does that report include?</li>
                        <li>What happens if my home hasn't sold in 30 days? What is your re-pricing strategy?</li>
                        <li>How many listings are you currently managing, and who will handle showings and inquiries?</li>
                    </ul>

                    <h3>Credentials and Standing</h3>
                    <p>In BC, all real estate agents must be licensed by the BC Financial Services Authority (BCFSA). Beyond basic licensing, look for designations like REALTOR&reg; (membership in a real estate board), and tenure in the industry. An agent who has been licensed through multiple market cycles &mdash; bull markets, bear markets, and everything in between &mdash; has negotiating experience that a newer agent simply cannot replicate. Les Twarog has been licensed since 1988 and has operated through every major BC market cycle of the past 36 years.</p>

                    <div class="sg-callout">
                        <div class="sg-callout-label">Expert Note</div>
                        <p>Never choose a listing agent based on commission alone. An agent offering a lower commission but delivering fewer showings, a weaker buyer network, and a lower sale price will cost you far more than the commission savings. Focus on net proceeds — what you walk away with after commission — not the commission rate in isolation.</p>
