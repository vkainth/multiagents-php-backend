                    <h2 style="font-size:28px;font-weight:700;margin-bottom:8px;font-family:roboto,sans-serif;color:#1a1a2e;">Seller FAQ: Common Questions About BC Real Estate</h2>
                    <p style="color:#666;font-size:15px;margin-bottom:32px;">Answers to the questions BC home sellers ask most — commissions, timelines, market mechanics, and legal processes.</p>

                    <div class="sg-faq-list">

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">What commission does a listing agent charge in BC?</button>
                            <div class="sg-faq-answer">
                                <p>In British Columbia, real estate commissions are not fixed by law — they are fully negotiable between the seller and their listing agent. A typical commission structure in Greater Vancouver is around 3.5% on the first $100,000 and 1.5% on the remainder of the sale price, split between the buyer's agent and the listing agent. The actual split of that total fee between the listing brokerage and the buyer's brokerage is determined by the listing agreement. Always confirm the full commission structure in writing before signing.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">How do I know if my listing agent is performing?</button>
                            <div class="sg-faq-answer">
                                <p>Key performance indicators include: (1) Days on market (DOM) — how long comparable homes with that agent sell relative to the neighbourhood average; (2) List-to-sold price ratio — how close the final sale price is to the list price; (3) Number of showings per week — an active listing typically generates 3–8 showings in the first two weeks; (4) Buyer feedback — your agent should relay feedback from every showing within 24 hours; (5) Weekly reports — professional agents provide weekly updates on views, inquiries, and comparable sales. If you are not receiving these updates, have a direct conversation with your agent about expectations.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">What is a list-to-sold ratio in real estate?</button>
                            <div class="sg-faq-answer">
                                <p>The list-to-sold ratio (also called the sale-price-to-list-price ratio) measures the final sale price as a percentage of the original list price. A ratio of 100% means the home sold at exactly asking. A ratio above 100% (e.g. 103%) means it sold above asking — common in a seller's market. A ratio below 100% (e.g. 97%) means it sold below asking. Tracking this ratio for your specific neighbourhood and property type gives you a realistic expectation of what your home will fetch and helps you calibrate your list price strategy. View live ratios by area on the <a href="/market-report" style="color:#1a6baa;">BC Condos And Homes market report pages</a>.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">What is days on market (DOM) and why does it matter?</button>
                            <div class="sg-faq-answer">
                                <p>Days on market (DOM) is the number of calendar days between when a property is first listed on MLS and when it receives an accepted offer. A low DOM indicates strong demand. A high DOM may indicate overpricing, presentation issues, or softening demand — and it signals weakness to buyers, who use DOM as a negotiating tool. In Greater Vancouver, average DOM varies significantly by property type and neighbourhood. Reviewing average DOM in your submarket before listing is essential for setting a realistic pricing and timing strategy.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">What is the difference between list price and sold price?</button>
                            <div class="sg-faq-answer">
                                <p>The list price is the asking price when a property is first advertised. The sold price is the final agreed price at the time of an accepted offer. In a seller's market, sold prices frequently exceed list prices due to competing offers. In a buyer's market, properties often sell below asking. The difference between these two figures — the list-to-sold ratio — is one of the most useful data points when deciding how to price your home. It tells you how the market is actually transacting, not just what sellers are hoping to achieve.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">Does the seller pay the buyer's agent commission in BC?</button>
                            <div class="sg-faq-answer">
                                <p>Yes — in BC, it is standard practice for the seller to fund both the listing agent commission and the buyer's agent commission out of the sale proceeds. The buyer's agent commission (cooperating brokerage commission) is specified in your listing agreement and is offered to buyer's agents as an incentive to bring qualified offers. If you offer a below-market buyer's agent commission, some buyer's agents may be less motivated to show your property — reducing your pool of offers. Always discuss the buyer's agent commission structure with your listing agent as part of your overall marketing strategy.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">How long does closing take after an accepted offer in BC?</button>
                            <div class="sg-faq-answer">
                                <p>The typical closing period in BC is 30–90 days from accepted offer to completion (the date ownership legally transfers). The process involves: a subject removal period (usually 7–14 business days) during which the buyer confirms financing, conducts inspections, and reviews strata documents; followed by a firm deal once subjects are removed; then completion (funds transferred, title changes hands); and finally possession (buyer takes keys, usually one day after completion). Your notary or lawyer handles the conveyancing on your behalf.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">What is a subject removal in BC?</button>
                            <div class="sg-faq-answer">
                                <p>A subject removal is when the buyer formally removes the conditions written into their offer — most commonly financing approval, home inspection, and review of strata documents. Until subjects are removed, the deal is conditional and either party can walk away without penalty. Once subjects are removed in writing, the deal becomes firm and binding. Sellers cannot accept other offers while a subject offer is pending, though a "72-hour clause" can sometimes be negotiated to allow the seller to continue marketing and force the buyer to decide.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">Can I sell my home without an agent in BC?</button>
                            <div class="sg-faq-answer">
                                <p>Yes — BC law does not require a real estate agent for a private sale (FSBO — For Sale By Owner). However, FSBO sellers do not have access to MLS, limiting buyer reach significantly. Without MLS, your listing is typically seen by a small fraction of active buyers compared to an MLS-listed property. Research consistently shows that MLS-listed properties sell faster and for a higher net price on average than FSBO properties, even after accounting for commission. If you choose to sell privately, engage a real estate lawyer or notary to handle the legal paperwork and ensure the contract is properly drafted.</p>
                            </div>
                        </div>

                        <div class="sg-faq-item">
                            <button class="sg-faq-toggle" aria-expanded="false">What is a strata property and what do sellers need to disclose?</button>
                            <div class="sg-faq-answer">
                                <p>A strata property is one where individual owners hold title to their unit while sharing ownership of common areas (lobby, amenities, parking structure, building envelope) with other owners. Condos, townhouses, and some commercial units are typically strata properties. When selling a strata property, you must provide buyers with strata documents including the Form B Information Certificate, strata minutes (last 2 years), bylaws, rules, financial statements, and depreciation report. Buyers review these during their subject period. Significant upcoming special levies, litigation history, or deferred maintenance shown in these documents can affect your property's market value and buyer interest. Request updated strata documents from your strata management company before listing.</p>
                            </div>
