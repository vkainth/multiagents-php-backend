            <div id="half-vs-full" class="mfg-section">
                <h2>1. Half-Duplex vs Full Duplex: What's the Difference?</h2>
                <p>The term "duplex" covers two distinct ownership structures in Metro Vancouver:</p>

                <div class="mfg-comparison">
                    <div class="mfg-comp-col mfg-col-a">
                        <h4>Full Duplex (Whole Building)</h4>
                        <ul>
                            <li>One title covers the entire building and both units</li>
                            <li>Owner collects rent from <em>both</em> units</li>
                            <li>No strata council, no strata fees</li>
                            <li>Higher purchase price but stronger cash flow</li>
                            <li>Full control over tenancy, renovations, and management</li>
                            <li>Can live in one unit and rent the other</li>
                        </ul>
                    </div>
                    <div class="mfg-comp-col mfg-col-b">
                        <h4>Half-Duplex (One Unit)</h4>
                        <ul>
                            <li>You own one unit; neighbour owns the other</li>
                            <li>Usually a strata or bare-land strata structure</li>
                            <li>Monthly strata fees ($80–$300) for shared insurance/common property</li>
                            <li>Lower purchase price — more accessible entry point</li>
                            <li>Ideal for owner-occupancy with a rental suite</li>
                            <li>Shared party wall — noise separation matters</li>
                        </ul>
                    </div>
                </div>

                <div class="mfg-callout">
                    <div class="mfg-callout-label">Pro Tip</div>
                    <p>Many Metro Vancouver "half-duplexes" are technically Strata Duplexes — two-unit stratas with no amenities and very low strata fees. Confirm the legal structure before assuming the governance and cost implications.</p>
                </div>
            </div>

            <div id="pros-buying-duplex" class="mfg-section">
                <h2>2. Why Buy a Duplex in BC?</h2>

                <h3>Rental Income Offsets Your Mortgage</h3>
                <p>The defining advantage of a duplex purchase is the ability to use rental income from the second unit to offset your mortgage cost. In Metro Vancouver, a suite in a duplex can generate $1,800–$2,800/month depending on the city, unit size, and condition. This rental income is factored into mortgage qualification (typically at 50% of market rent by most lenders), allowing buyers to qualify for a larger mortgage than they could on a single-family home of the same price.</p>

                <h3>Multi-Generational Living</h3>
                <p>A full duplex is an ideal vehicle for multi-generational families — parents in one unit, grown children in the other. This arrangement provides financial support through shared ownership while maintaining independent living spaces with separate entrances, kitchens, and utilities.</p>

                <h3>Lower Entry Price Than Detached</h3>
                <p>In cities like Burnaby and Vancouver, a half-duplex often starts $200,000–$400,000 below a comparable detached home, while still providing more space, a yard, and no shared walls on three sides. For buyers priced out of detached homes who don't want the restrictions of strata condo life, a half-duplex occupies a compelling middle ground.</p>

                <h3>SSMUH Redevelopment Potential</h3>
                <p>Under BC's <a href="/ssmuh-guide">Small-Scale Multi-Unit Housing (SSMUH)</a> legislation, the lot your duplex sits on may now permit 3–4 units by right. This means a future owner could potentially redevelop the site to add density, enhancing the land's long-term value. Always ask your agent to run a density check on any lot you're considering.</p>
            </div>

            <div id="parking" class="mfg-section">
                <h2>3. Parking Reality: What to Expect and Why It Matters</h2>
                <p>Parking is one of the most consequential — and most underestimated — factors in duplex ownership. It affects tenant satisfaction, rental rates, and future resale value. Here's what you'll actually encounter in Metro Vancouver:</p>

                <div class="mfg-parking-grid">
                    <div class="mfg-parking-card">
                        <h4>Attached Single or Double Garage</h4>
                        <span class="mfg-pk-score" style="background:#d4edda;color:#155724;">Best</span>
                        <p>Covered parking accessed from inside or directly adjacent to the unit. Ideal for the owner's unit. Doubles as storage. Most attractive to buyers and tenants alike. Adds resale value.</p>
                    </div>
                    <div class="mfg-parking-card">
                        <h4>Detached Garage (Lane or Rear)</h4>
                        <span class="mfg-pk-score" style="background:#d1ecf1;color:#0c5460;">Good</span>
                        <p>Covered parking at the back of the lot, often accessed via the lane. Less convenient than attached but still highly desirable — and opens redevelopment potential for a carriage house.</p>
                    </div>
                    <div class="mfg-parking-card">
                        <h4>Open Concrete Pad</h4>
                        <span class="mfg-pk-score" style="background:#fff3cd;color:#856404;">Adequate</span>
                        <p>Uncovered off-street stall on the property. Common in older duplexes. Functional but less attractive to tenants in rain-heavy cities. One or two pads for the full building is the norm.</p>
                    </div>
                    <div class="mfg-parking-card">
                        <h4>Street Only (No Off-Street)</h4>
                        <span class="mfg-pk-score" style="background:#f8d7da;color:#721c24;">Challenging</span>
                        <p>No off-street parking. Common in older pre-car Vancouver duplexes. Severely limits tenant pool in car-dependent areas. Can reduce rents by $100–$200/month compared to similar units with parking. Hardest to resell.</p>
                    </div>
                </div>

                <div class="mfg-warning">
                    <div class="mfg-warning-label">What Agents Don't Always Tell You</div>
                    <p>In many older Metro Vancouver duplexes, both units share a single concrete pad or street parking. This creates friction between tenants — especially when both units have multiple-car families. Ask specifically: how many off-street stalls exist, how they are allocated between units, and whether that is formalized in a strata bylaw or rental agreement.</p>
                </div>
            </div>

            <div id="legal-suites" class="mfg-section">
                <h2>4. Legal vs Illegal Suites: How to Tell the Difference</h2>
                <p>An enormous number of Metro Vancouver duplexes have secondary suites — basement or ground-floor units — that are not permitted. This is a critical issue for buyers: illegal suites carry insurance risk, mortgage qualification complications, municipal enforcement exposure, and liability if a tenant is injured in a non-code-compliant space.</p>

                <h3>How to Verify Suite Legality</h3>
                <ol>
                    <li><strong>Request building permits from the city.</strong> Contact the municipal building department by address and ask for a permit history. A legal suite will have a permit on file. Many cities now offer this lookup online.</li>
                    <li><strong>Check the BC Assessment.</strong> Legal suites are often assessed as a two-family dwelling. If the assessment shows it as a single-family home but two kitchens are visible, that's a red flag.</li>
                    <li><strong>Have your inspector look for compliance signs.</strong> A legal suite needs: minimum 1.95m ceiling height, egress window in sleeping areas, interconnected smoke alarms, separate electrical panel or sub-panel, and a fire separation (usually a one-hour fire assembly between the suite and the rest of the dwelling).</li>
                    <li><strong>Include a subject-to-permit-review in your offer.</strong> Your agent can write this condition to allow you to request and review all city permits for the property before committing.</li>
                </ol>

                <h3>The Risk of an Illegal Suite</h3>
                <ul>
                    <li><strong>Insurance:</strong> Most home insurance policies exclude or limit coverage for losses related to non-permitted suites. A fire in an illegal suite could leave you significantly underinsured.</li>
                    <li><strong>City enforcement:</strong> If a neighbour complains, a city inspector can order the suite closed — eliminating your rental income and triggering costly renovation requirements.</li>
                    <li><strong>Mortgage qualification:</strong> Many lenders will not count rental income from an illegal suite when calculating your qualifying income. This affects how much you can borrow.</li>
                    <li><strong>Tenancy liability:</strong> Injuries to tenants in non-code-compliant spaces (inadequate egress, no smoke alarm interconnection) expose the owner to significant liability.</li>
                </ul>

                <div class="mfg-callout">
                    <div class="mfg-callout-label">What to Do if the Suite Is Not Permitted</div>
                    <p>In most Metro Vancouver municipalities, legalizing an existing suite costs $5,000–$15,000 in permits, contractor work, and inspections — and can be done without demolishing and rebuilding, if the suite is close to code. Get an estimate before closing. This cost can often be negotiated into the purchase price.</p>
                </div>
            </div>

            <div id="strata-vs-freehold" class="mfg-section">
                <h2>5. Strata Duplex vs Freehold Duplex</h2>
                <p>Understanding the title structure of a duplex is essential before you make an offer.</p>

                <h3>Freehold (Fee Simple) Full Duplex</h3>
                <p>The buyer owns the entire building and the land under it. There is no strata corporation, no strata fees, and no shared governance. The owner is entirely responsible for all maintenance, insurance, and repairs on the full building. This is the ownership structure of a full duplex where one owner holds both units.</p>

                <h3>Strata Half-Duplex (Two-Unit Strata)</h3>
                <p>Each half of the duplex is a separate strata lot. The two owners share common property (the lot boundary, any shared driveway or utilities). A strata corporation governs the shared elements, and each owner pays monthly strata fees — typically $100–$350 for a half-duplex with minimal common property. The strata has bylaws that govern things like pets, rentals, and exterior modifications.</p>

                <h3>Bare-Land Strata Half-Duplex</h3>
                <p>A bare-land strata means each owner owns the building on their portion of the land in fee simple, with the strata corporation owning only a common area (often just the shared driveway). This is the most freehold-like of the strata structures and is common in newer half-duplex developments.</p>

                <div class="mfg-warning">
                    <div class="mfg-warning-label">Review the Strata Documents</div>
                    <p>Even a small two-unit strata has bylaws. Review them carefully — some have rental restrictions, pet bylaws, or approval requirements for suites. For a half-duplex with a rental suite, make sure the strata's rental bylaws permit you to rent both the main unit and the suite.</p>
                </div>
            </div>

            <div id="inspection" class="mfg-section">
                <h2>6. What a Duplex Inspection Must Cover</h2>
                <p>A duplex inspection requires an inspector with multi-unit experience. Beyond the standard single-family checklist, make sure your inspection covers:</p>
                <ul>
                    <li><strong>Electrical panels:</strong> Each unit should have a separate panel (minimum 100 amp, ideally 200 amp per unit). Knob-and-tube wiring is an insurance risk — many insurers refuse to cover it or charge significant premiums.</li>
                    <li><strong>Separate shut-offs:</strong> Verify that each unit has its own water shut-off, electrical disconnect, and if gas is present, gas shut-off. Shared systems create operational headaches when one tenant needs service.</li>
                    <li><strong>Sound separation:</strong> Request the inspector test between-floor sound isolation. Inadequate acoustic separation is the #1 complaint in older duplexes and directly affects tenant retention and rent levels.</li>
                    <li><strong>Roof condition:</strong> In a full duplex, both halves share the same roof structure. A failing roof affects both units and can cost $30,000–$70,000 to replace on a full duplex.</li>
                    <li><strong>Heating systems:</strong> Are the units on separate furnaces? Shared heating is a management problem — one unit controls the thermostat but both pay the consequences.</li>
                    <li><strong>Foundation and drainage:</strong> Basements in older duplexes are common locations for suites. Check foundation walls for moisture, efflorescence (white mineral deposits indicating water movement), and cracking.</li>
                    <li><strong>Egress from the suite:</strong> The sleeping rooms in the suite must have windows large enough for emergency egress under BC Building Code. A bedroom with a small or barred window may fail this requirement.</li>
                </ul>
            </div>

            <div id="financing" class="mfg-section">
                <h2>7. Duplex Financing in BC</h2>

                <h3>Owner-Occupied Duplex</h3>
                <p>If you plan to live in one unit and rent the other, most lenders treat the purchase as a residential mortgage, not a commercial one. You can typically include 50–80% of the rental income from the second unit when calculating your qualifying income. This rental offset is one of the most powerful financial tools a duplex buyer has — it can increase your qualifying purchase price by $200,000–$400,000 compared to buying a single-family home without rental income.</p>

                <h3>Down Payment Requirements</h3>
                <ul>
                    <li>Under $500,000: Minimum 5% down</li>
                    <li>$500,001–$999,999: 5% on first $500K + 10% on the remainder</li>
                    <li>$1,000,000+: Minimum 20% down (no CMHC insured mortgages above $999,999)</li>
                </ul>
                <p>Given that most Metro Vancouver duplexes list above $1.2M, a 20% down payment is the practical minimum for most buyers — meaning $240,000 or more on a typical full duplex.</p>

                <h3>Investment (Non-Owner-Occupied) Duplex</h3>
                <p>If you will not live in either unit, the property is classified as an investment property. Investment mortgages in Canada require a minimum 20% down payment and typically carry a rate premium of 0.15–0.50% over owner-occupied rates. Lenders still allow rental income to be factored into qualifying, but at varying percentages (50–100% depending on lender and documentation provided).</p>

