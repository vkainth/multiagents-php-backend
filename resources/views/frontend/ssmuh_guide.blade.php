            <div id="what-is-ssmuh" class="mfg-section">
                <h2>1. What Is SSMUH and Why Did BC Pass It?</h2>
                <p>Small-Scale Multi-Unit Housing (SSMUH) refers to BC's November 2023 legislation — formally Bill 44, the <em>Housing Statutes (Residential Development) Amendment Act</em> — that requires municipalities to allow a minimum of 3 to 6 residential units on lots previously zoned for a single-family or duplex home.</p>
                <p>The legislation was introduced in response to BC's severe housing shortage. For decades, local zoning bylaws restricted most residential land to single-family use, preventing gentle intensification even on large lots steps from transit. By mandating multi-unit zoning across the province, the BC government aims to increase housing supply without requiring large-scale rezoning campaigns or developer applications.</p>

                <h3>Key Dates</h3>
                <ul>
                    <li><strong>November 2023:</strong> Bill 44 receives Royal Assent.</li>
                    <li><strong>June 2024:</strong> Municipalities with populations over 5,000 required to update zoning bylaws to comply.</li>
                    <li><strong>2024 onward:</strong> Smaller municipalities phased in on their own timelines.</li>
                </ul>

                <div class="mfg-callout">
                    <div class="mfg-callout-label">Key Insight</div>
                    <p>SSMUH doesn't force anyone to build — it removes the bureaucratic barrier to building. A lot owner can still maintain their single-family home as-is. The legislation simply means they no longer need to apply for rezoning to add legal secondary suites, a carriage house, or a fourplex.</p>
                </div>
            </div>

