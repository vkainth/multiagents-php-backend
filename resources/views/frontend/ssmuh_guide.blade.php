            <div id="4-units-by-right" class="mfg-section">
                <h2>3. What Does 4 Units By Right Actually Mean?</h2>
                <p>"By right" means that a property owner is <strong>permitted to build</strong> a specified number of units without needing to apply for rezoning — the most time-consuming and uncertain part of any development process. Under SSMUH, up to 4 units are allowed by right on most residential lots; up to 6 units are allowed on lots that are:</p>
                <ul>
                    <li>Within 400 metres of a bus stop with at least 20 buses per day, <em>or</em></li>
                    <li>Within 200 metres of a bus stop with at least 40 buses per day, <em>or</em></li>
                    <li>Near SkyTrain stations (subject to Transit-Oriented Areas legislation, a companion bill)</li>
                </ul>
                <h3>What Can Be Built?</h3>
                <p>The 4 (or 6) units can take many forms, depending on site constraints:</p>
                <ul>
                    <li>Fourplex (4 units in a single building)</li>
                    <li>Triplex + secondary suite or laneway house</li>
                    <li>Duplex + carriage house/coach house</li>
                    <li>Duplex + secondary suite in each half</li>
                    <li>Single-family home + 3 detached accessory dwelling units (ADUs)</li>
                </ul>
                <h3>What "By Right" Does NOT Mean</h3>
                <p>By right means no rezoning — but it does not exempt you from building permits, development permits, Development Cost Charges (DCCs), or compliance with building codes. You still need to go through the city's normal permitting process. By-right simply means the <em>land use</em> is already approved; the <em>specific project</em> still needs its own permit.</p>
            </div>

            <div id="implications" class="mfg-section">
                <h2>4. Implications for Buyers and Existing Multi-Family Owners</h2>

                <h3>For First-Time Buyers and Investors</h3>
                <p>SSMUH opens a compelling new investment strategy: purchasing a modest single-family home on a qualifying lot, retaining or renting the existing house while obtaining permits to add additional units, and gradually building a multi-unit rental portfolio without commercial financing. This "buy, hold, and add" approach is now viable in cities that previously required expensive rezoning applications.</p>

                <h3>For Existing Duplex and Fourplex Owners</h3>
                <p>Existing multi-family properties — particularly older duplexes and fourplexes — still deliver reliable rental income. However, SSMUH creates new competition from freshly built multi-unit properties on previously single-family lots. The net effect on value depends on your specific property:</p>
                <ul>
                    <li><strong>Larger lots with redevelopment potential:</strong> May see increased demand as buyers acquire both the income property and the future development optionality.</li>
                    <li><strong>Smaller, older properties in average condition:</strong> Face pricing pressure as new-build alternatives become more accessible.</li>
                    <li><strong>Well-maintained properties with legal suites and good parking:</strong> Continue to command premiums regardless of SSMUH because they are ready to operate immediately.</li>
                </ul>

                <h3>For Sellers of Multi-Family Properties</h3>
                <p>If you are selling a duplex or fourplex on a large lot in a qualifying SSMUH municipality, the redevelopment potential is now a legitimate selling point. Have your agent quantify the density potential — how many units could be built under SSMUH — and include that analysis in your marketing materials.</p>
            </div>

            <div id="questions-to-ask" class="mfg-section">
                <h2>5. Questions to Ask Before Buying on an SSMUH-Zoned Lot</h2>
                <p>Before purchasing a property specifically to leverage SSMUH density, due diligence requires more than checking the zoning. Ask the following:</p>

                <h3>Zoning &amp; Density</h3>
                <ul>
                    <li>Has the municipality updated its zoning bylaw to comply with SSMUH? (Most have; a few are pending.)</li>
                    <li>What is the maximum number of units allowed on this specific lot?</li>
                    <li>Is the lot within a transit corridor that qualifies for 6 units instead of 4?</li>
                    <li>Are there any heritage overlays, flood plains, or environmental designations that could restrict density?</li>
                </ul>

                <h3>Site Constraints</h3>
                <ul>
                    <li>What are the setback requirements from property lines (front, rear, side) for new units?</li>
                    <li>What is the maximum lot coverage percentage for buildings?</li>
                    <li>What is the maximum building height? Does the bylaw allow 3-storey structures?</li>
                    <li>Is the lot large enough to physically accommodate the footprint of multiple buildings or a larger structure?</li>
                </ul>

                <h3>Servicing &amp; Infrastructure</h3>
                <ul>
                    <li>What size is the existing water service connection — 19mm or 25mm? (4-unit buildings often need 25mm.)</li>
                    <li>What size is the existing sewer lateral — 100mm or 150mm? Does it have capacity for additional units?</li>
                    <li>Is there lane access? A back lane dramatically increases development options, including carriage houses.</li>
                    <li>What Development Cost Charges (DCCs) will apply per added unit?</li>
                </ul>

                <h3>Parking</h3>
                <ul>
                    <li>Does the municipality require on-site parking per unit? (Near transit, the answer is often no.)</li>
                    <li>If parking is required, is there enough lot area to provide stalls while meeting setbacks?</li>
                    <li>Is street parking available and unrestricted? This matters for tenant satisfaction.</li>
                </ul>

                <div class="mfg-callout">
                    <div class="mfg-callout-label">Expert Tip</div>
                    <p>Commission a pre-purchase feasibility letter from a licensed architect or residential designer. For $500–$1,500, they can tell you exactly what can be built on the lot, what permits are required, and a rough cost estimate. This is money well spent before a $1.5M+ purchase.</p>
                </div>
            </div>

            <div id="resale-value" class="mfg-section">
                <h2>6. How SSMUH Affects Resale Value</h2>
                <p>The impact of SSMUH on property values is nuanced and continues to evolve as the market digests the legislation. Here is what the current data and experience suggest:</p>

                <h3>Land Value Premium</h3>
                <p>Lots that are large enough to support the maximum allowable density under SSMUH are being priced at a premium relative to smaller lots in the same area. Buyers are essentially purchasing an option on future development. This is most visible in Burnaby and Vancouver where 33' × 122' lots near SkyTrain have seen increased investor interest.</p>

                <h3>Existing Income Property Value</h3>
                <p>Well-maintained duplexes and fourplexes with legal suites, good parking, and current electrical (200-amp panels per unit) continue to trade at strong multiples. Buyers who want rental income <em>today</em> — without the 12–24 month permitting and construction cycle — pay a meaningful premium for turnkey income properties.</p>

                <h3>Older, Non-Conforming Multi-Family</h3>
                <p>Older multi-family properties in poor condition, with non-permitted suites, outdated wiring, or deferred maintenance may become relatively less attractive as SSMUH makes new-build alternatives easier. Sellers of these properties need realistic pricing expectations in 2025 and beyond.</p>

