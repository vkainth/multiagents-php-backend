                        <div class="bg-faq-answer">
                            <p>Property Transfer Tax is a provincial tax paid by the buyer at the time of registration of any real estate purchase in BC. Standard rates: 1% on the first $200,000; 2% on $200,001 to $2,000,000; 3% above $2,000,000; plus an additional 2% on the portion above $3,000,000 for residential properties. On an $800,000 purchase, PTT is approximately $14,000. Exemptions include the First-Time Home Buyer Exemption (full exemption for qualifying purchases up to $835,000 fair market value) and the Newly Built Home Exemption. Your notary or real estate lawyer will calculate and remit PTT on your behalf as part of the conveyancing process.</p>
