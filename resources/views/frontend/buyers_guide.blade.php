        document.querySelectorAll('.bg-faq-toggle').forEach(function(b) { b.classList.remove('active'); b.setAttribute('aria-expanded', 'false'); });
        if (!isOpen) {
            answer.classList.add('open');
            this.classList.add('active');
            this.setAttribute('aria-expanded', 'true');
        }
    });
});
