                            <p>A depreciation report is a professional engineering assessment of a strata corporation's common property — the roof, elevators, plumbing systems, parking structure, and other shared building components. It estimates the remaining service life of each element and the cost to repair or replace it over a 30-year horizon. For buyers, the depreciation report is critical because it reveals whether the strata's contingency reserve fund is adequately funded. If the reserve is chronically underfunded and major repairs are coming, strata owners will likely face a special levy — a one-time lump-sum payment that all owners must contribute to fund the repair. Reviewing the depreciation report and financial statements during your subject period is a non-negotiable step when buying a strata property in BC.</p>
