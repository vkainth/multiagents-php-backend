                        <div class="bg-faq-answer">
                            <p>The BC First-Time Home Buyer Exemption eliminates or reduces the Property Transfer Tax for eligible first-time buyers. The full exemption applies to purchases of $500,000 or less, with a partial exemption on the portion between $500,000 and $525,000. To qualify, you must be a Canadian citizen or permanent resident, have never owned a principal residence anywhere in the world, have lived in BC for at least 12 consecutive months before the purchase, and intend to occupy the property as your principal residence within 92 days of registration. The property's fair market value must not exceed $835,000 for the newly built home exemption variant. The PTT savings can be significant — on a $500,000 property the standard PTT would be approximately $8,000, which is fully waived for qualifying first-time buyers.</p>
