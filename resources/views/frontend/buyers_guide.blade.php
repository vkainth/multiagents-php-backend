                            <p>The minimum down payment in Canada depends on the purchase price: 5% for homes up to $500,000; 5% on the first $500,000 plus 10% on the portion between $500,000 and $999,999; and 20% for homes priced at $1,000,000 or more (these do not qualify for insured mortgages). Any purchase with less than 20% down requires CMHC mortgage default insurance. Given Metro Vancouver's prices, many buyers also consider saving 20% or more to avoid the insurance premium and access more competitive mortgage rates. Your mortgage broker can help you model different down payment scenarios and their impact on your monthly payments and total cost of borrowing.</p>
