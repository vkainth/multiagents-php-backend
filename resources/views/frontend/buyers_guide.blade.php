                            <p>BC's Foreign Buyer Tax — formally called the Additional Property Transfer Tax — is a 20% tax on the fair market value of residential property purchased by foreign nationals (non-Canadian citizens or permanent residents) in designated areas including Greater Vancouver, Victoria, Fraser Valley, Nanaimo, and the Central Okanagan. It is paid at registration in addition to the standard PTT. The tax was introduced in 2016 and increased to 20% in 2018. Canadian citizens and permanent residents are exempt. If a purchase is made jointly and one buyer is a foreign national, the tax applies proportionally to that buyer's share. Always confirm your tax status with a BC notary or real estate lawyer before signing an offer.</p>
