                    <h2>2. Mortgage Pre-Approval: What You Need and How It Works</h2>
                    <p>Getting pre-approved for a mortgage before you start viewing properties is essential in BC's competitive market. Pre-approval gives you a clear budget, demonstrates seriousness to sellers, and locks in an interest rate for 90 to 130 days while you search.</p>

                    <h3>The Pre-Approval Process</h3>
                    <div class="bg-step">
                        <div class="bg-step-num">1</div>
                        <div class="bg-step-body">
                            <h4>Choose a Lender or Mortgage Broker</h4>
                            <p>You can apply directly with a bank or credit union, or work with a mortgage broker who has access to multiple lenders. Brokers often negotiate better rates and can match you with specialized products that banks do not offer directly. There is no cost to you for using a broker — they are paid by the lender.</p>
                        </div>
                    </div>
                    <div class="bg-step">
                        <div class="bg-step-num">2</div>
                        <div class="bg-step-body">
                            <h4>Gather Your Documents</h4>
                            <p>Typical documents required: two recent pay stubs, T4 slips from the last two years, Notices of Assessment (NOA) from the CRA for the last two years, three months of bank statements, and details of any debts, car loans, or credit cards. Self-employed applicants typically need two years of financial statements and may need a larger down payment.</p>
                        </div>
                    </div>
                    <div class="bg-step">
                        <div class="bg-step-num">3</div>
                        <div class="bg-step-body">
                            <h4>Understand the Stress Test</h4>
                            <p>All federally regulated lenders in Canada require you to qualify at the higher of the Bank of Canada's qualifying rate (5.25% as of writing) or your contract rate plus 2%. This "stress test" ensures you can still afford your payments if interest rates rise. The stress test reduces the maximum mortgage you qualify for relative to the face rate alone.</p>
                        </div>
                    </div>
                    <div class="bg-step">
                        <div class="bg-step-num">4</div>
                        <div class="bg-step-body">
                            <h4>Receive Your Pre-Approval Letter</h4>
                            <p>A pre-approval letter confirms the maximum mortgage amount, the interest rate held, and the expiry date. Keep in mind that pre-approval is conditional — the lender still conducts full underwriting on the specific property once you have an accepted offer. Significant changes to your financial situation between pre-approval and closing (such as changing jobs or taking on new debt) can affect your final approval.</p>
                        </div>
                    </div>

                    <div class="bg-callout">
                        <div class="bg-callout-label">Important Note</div>
                        <p>Pre-approval is not the same as a mortgage commitment. Your lender's final approval is subject to the specific property appraising at or above the purchase price. If the property does not appraise, you may need to renegotiate the price, increase your down payment, or walk away during the subject period.</p>
                    </div>

                    <h3>How Much Mortgage Can You Afford?</h3>
                    <p>Canadian lenders use two key ratios to determine affordability. The Gross Debt Service (GDS) ratio must not exceed 39% — meaning your housing costs (mortgage payments, property taxes, strata fees, and heat) should not exceed 39% of your gross monthly income. The Total Debt Service (TDS) ratio must not exceed 44% — all debts (housing costs plus other loan payments) combined. Running these numbers with your mortgage broker before you start shopping ensures you are looking at properties you can genuinely afford.</p>
                </div>

                {{-- SECTION 3: Strata vs. Freehold --}}
                <div id="strata-vs-freehold" class="bg-section">
                    <h2>3. Strata vs. Freehold Properties: What to Look For</h2>
                    <p>The distinction between strata and freehold ownership is fundamental in BC, and affects your monthly costs, lifestyle, and the due diligence you need to conduct before buying.</p>

                    <div class="bg-comparison">
                        <div class="bg-comparison-col bg-col-strata">
                            <h4>Strata Properties</h4>
                            <ul>
                                <li>Condos, townhouses, duplexes, some commercial</li>
                                <li>You own your unit (strata lot) individually</li>
                                <li>Common areas shared with other owners</li>
                                <li>Monthly strata fees (operating + reserve fund)</li>
                                <li>Governed by strata council and bylaws</li>
                                <li>Pets, rentals, renovations may be restricted by bylaws</li>
                                <li>Review Form B, minutes, depreciation report, and financials</li>
                                <li>Risk of special levies if reserve fund is underfunded</li>
                            </ul>
                        </div>
                        <div class="bg-comparison-col bg-col-freehold">
                            <h4>Freehold Properties</h4>
                            <ul>
                                <li>Detached houses, some semi-detached</li>
                                <li>You own the building and the land</li>
                                <li>No shared governance or monthly strata fees</li>
                                <li>You are solely responsible for all maintenance</li>
                                <li>No bylaw restrictions on pets, rentals, or renovations</li>
                                <li>Greater autonomy over your property</li>
                                <li>Home inspection critical — no strata reserve to fall back on</li>
                                <li>Generally higher purchase price in Metro Vancouver</li>
                            </ul>
                        </div>
                    </div>

                    <h3>What to Look for in a Strata Property</h3>
                    <p>When evaluating a strata purchase, your subject period should include a thorough review of strata documents. Key items to assess:</p>
                    <ul>
                        <li><strong>Form B (Information Certificate):</strong> Confirms the current monthly strata fees, any outstanding special levies, and whether the seller owes money to the strata.</li>
                        <li><strong>Strata Meeting Minutes (2–3 years):</strong> Reveals ongoing issues, disputes, deferred maintenance, and planned repairs. Look for recurring complaints and any litigation mentions.</li>
                        <li><strong>Depreciation Report:</strong> Assesses the remaining life and replacement cost of all common property. A well-funded contingency reserve fund is a strong sign of responsible strata management.</li>
                        <li><strong>Financial Statements:</strong> Shows whether the strata is operating within budget and whether the contingency reserve fund is growing or being depleted.</li>
                        <li><strong>Bylaws and Rules:</strong> Governs what you can and cannot do in your unit — rental restrictions, pet policies, renovation approvals, parking, and noise rules.</li>
                    </ul>

                    <h3>What to Look for in a Freehold Property</h3>
                    <p>For freehold homes, a professional home inspection is your primary due diligence tool. Focus areas include the roof (age and condition), foundation, plumbing (age, type, and evidence of leaks), electrical (panel age and capacity), HVAC systems, insulation, and any evidence of moisture intrusion. In older homes (pre-1990), ask about asbestos and knob-and-tube wiring. In areas near the ocean or rivers, inquire about flood zone designations with your agent.</p>
                </div>

                {{-- SECTION 4: Making an Offer --}}
                <div id="making-an-offer" class="bg-section">
                    <h2>4. Making an Offer in BC</h2>
                    <p>When you find the right property, your agent will prepare a Contract of Purchase and Sale — BC's standard form for real estate offers. Understanding its key components helps you make strong, well-informed offers.</p>

                    <h3>Key Elements of a BC Offer</h3>
                    <ul>
                        <li><strong>Purchase Price:</strong> The price you are offering for the property.</li>
                        <li><strong>Deposit:</strong> Typically 5% of the purchase price, paid within 24 hours of an accepted offer. The deposit is held in trust and applied to your down payment at closing. It is at risk if you fail to complete the purchase after subjects are removed.</li>
                        <li><strong>Completion Date:</strong> The date on which legal ownership transfers and funds are paid. Typically 30 to 90 days from acceptance, negotiable between buyer and seller.</li>
                        <li><strong>Possession Date:</strong> When you receive the keys — usually one to two days after completion.</li>
                        <li><strong>Adjustment Date:</strong> Used to calculate the proration of property taxes, strata fees, and utilities between buyer and seller.</li>
                        <li><strong>Subjects (Conditions):</strong> Conditions that must be satisfied within a defined period before the deal becomes firm. Common subjects include financing, inspection, and strata document review.</li>
                        <li><strong>Included Items:</strong> Fixtures, appliances, and other items specifically included or excluded in the sale (e.g. a specific light fixture the seller wants to keep).</li>
                    </ul>

                    <h3>Setting Your Offer Price</h3>
                    <p>Your buyer's agent should prepare a Comparative Market Analysis (CMA) — a review of recent comparable sales in the immediate area — to help you determine fair market value. In a seller's market with multiple offers expected, you may need to offer above list price. In a buyer's market with longer days on market, there may be room to negotiate below list. Never rely solely on the list price as an indicator of value.</p>

                    <div class="bg-callout">
                        <div class="bg-callout-label">Multiple Offer Situations</div>
                        <p>When multiple buyers compete for the same property, the seller typically sets a deadline for all offers to be received. Your agent will advise on the most competitive price and terms. In some cases, sellers grant one opportunity for buyers to improve their offer before selecting. If you are in a multiple-offer situation, discuss with your agent whether presenting subject-free is appropriate given your level of pre-offer due diligence and financial position.</p>
                    </div>
                </div>

                {{-- SECTION 5: Understanding Subjects --}}
                <div id="subjects" class="bg-section">
                    <h2>5. Understanding Subjects and Conditions</h2>
                    <p>Subjects are the buyer's protection clauses in a BC real estate offer. They give you a defined window to investigate the property and confirm your financing before committing irrevocably to the purchase.</p>

                    <h3>Common Subject Conditions in BC</h3>
                    <ul>
                        <li><strong>Subject to Financing:</strong> Allows time to receive formal mortgage approval from your lender on this specific property. Typically 5–10 business days. If financing is denied, you can exit the contract and receive your deposit back.</li>
                        <li><strong>Subject to Home Inspection:</strong> Gives you the right to hire a professional inspector and review their findings. If significant deficiencies are identified, you can negotiate repairs, a price reduction, or exit the deal.</li>
                        <li><strong>Subject to Review of Strata Documents:</strong> For strata properties, allows you (and ideally a strata document review professional) to examine the Form B, minutes, depreciation report, financial statements, and bylaws. Concerns uncovered here may be grounds to renegotiate or withdraw.</li>
                        <li><strong>Subject to Sale of Buyer's Property:</strong> Gives the buyer time to sell an existing property before committing. Less commonly accepted by sellers in competitive markets — often paired with a 72-hour clause allowing the seller to continue marketing.</li>
                    </ul>

                    <h3>The Subject Removal Process</h3>
                    <p>Once your subjects have been satisfied, you sign a Subject Removal form removing all conditions in writing. This is the point of no return — the deal becomes firm and binding. Your deposit is no longer refundable if you fail to complete. From subject removal, your notary or lawyer takes over to manage the conveyancing process through to the completion date.</p>

                    <h3>Subject-Free Offers: When and Why</h3>
                    <p>In highly competitive situations, buyers sometimes present subject-free offers to differentiate themselves. This approach eliminates the subject period and signals maximum commitment to the seller. The risks are real: you are committing to purchase without confirmed financing, without an inspection, and — for strata — without reviewing the strata documents. Subject-free offers should only be considered when you have completed significant pre-offer due diligence, have pre-approval from a lender comfortable with the property type, and have the financial capacity to proceed regardless of what an inspection might reveal.</p>
                </div>

                {{-- SECTION 6: The Closing Process --}}
                <div id="closing" class="bg-section">
                    <h2>6. The Closing Process in BC</h2>
                    <p>After subjects are removed and the deal is firm, the closing process begins. Your notary or real estate lawyer handles the legal and financial steps between subject removal and the completion date.</p>

                    <h3>Step-by-Step: From Subject Removal to Keys</h3>
                    <div class="bg-step">
                        <div class="bg-step-num">1</div>
                        <div class="bg-step-body">
                            <h4>Engage Your Notary or Lawyer</h4>
                            <p>Your notary or real estate lawyer handles title search, mortgage registration, and all financial transfers. They confirm clear title (no liens, easements, or encumbrances that affect your ownership rights), prepare the closing documents, and disburse funds on the completion date.</p>
                        </div>
                    </div>
                    <div class="bg-step">
                        <div class="bg-step-num">2</div>
                        <div class="bg-step-body">
                            <h4>Finalize Your Mortgage</h4>
                            <p>Your lender requires a signed copy of the Contract of Purchase and Sale to proceed with full underwriting. They will order a property appraisal if required. Once approved, they issue mortgage instructions to your notary or lawyer.</p>
                        </div>
                    </div>
                    <div class="bg-step">
                        <div class="bg-step-num">3</div>
                        <div class="bg-step-body">
                            <h4>Pre-Completion Walk-Through</h4>
                            <p>You are typically entitled to one pre-completion inspection of the property (often the day before or morning of completion) to confirm it is in the same condition as when you offered, that agreed-upon inclusions are present, and that no damage has occurred. This is not a second inspection — it is a verification walk-through.</p>
                        </div>
                    </div>
                    <div class="bg-step">
                        <div class="bg-step-num">4</div>
                        <div class="bg-step-body">
                            <h4>Completion Day</h4>
                            <p>Your notary or lawyer transfers the mortgage funds and your down payment to the seller's notary. Once funds are confirmed received, the Land Title Office registers the transfer and your name is recorded as the new owner. This typically happens by mid-afternoon on the completion date.</p>
                        </div>
                    </div>
                    <div class="bg-step">
                        <div class="bg-step-num">5</div>
                        <div class="bg-step-body">
                            <h4>Possession Day</h4>
                            <p>Typically one to two days after completion, you receive the keys from the listing agent or seller directly. The property should be vacant, broom-clean, and in the agreed condition. You are now a homeowner.</p>
                        </div>
                    </div>
                </div>

                {{-- SECTION 7: Understanding Your Costs --}}
                <div id="costs" class="bg-section">
                    <h2>7. Understanding Your Costs as a BC Buyer</h2>
                    <p>Beyond the purchase price and down payment, buyers in BC face a range of closing costs. Budgeting for these in advance prevents surprises at the completion table.</p>

                    <h3>Property Transfer Tax (PTT)</h3>
                    <p>BC's Property Transfer Tax is paid at closing on every registered purchase. Standard rates: 1% on the first $200,000; 2% on $200,001–$2,000,000; 3% above $2,000,000; and an additional 2% on the portion over $3,000,000. On an $800,000 purchase, PTT is approximately $14,000. The First-Time Home Buyer Exemption (FTHB) and Newly Built Home Exemption can eliminate or reduce this cost if you qualify.</p>

                    <h3>Legal / Notary Fees</h3>
                    <p>Notary or lawyer fees for a standard residential purchase typically range from $1,200 to $2,500, including disbursements (title searches, Land Title Office registration fees, courier, and other transaction costs).</p>

                    <h3>Home Inspection</h3>
                    <p>A professional home inspection costs $450 to $800 for most Metro Vancouver properties. Larger or older homes may cost more. Always use a CAHPI or ASTTBC certified inspector. For strata properties, also budget $150–$400 for a strata document review if you use a specialist.</p>

                    <h3>CMHC Mortgage Insurance</h3>
                    <p>If your down payment is less than 20%, mortgage default insurance is mandatory. The premium is 0.60% to 4.00% of the insured mortgage amount, added to your mortgage balance. On a $700,000 purchase with 10% down ($70,000), the insured mortgage is $630,000 and the premium at the standard 3.10% rate would be approximately $19,530 — added to your mortgage, not paid at closing as cash.</p>

                    <h3>Title Insurance</h3>
                    <p>A one-time premium of approximately $200–$300, title insurance protects you against title fraud, survey errors, existing encumbrances, and other defects not found in a standard title search. Most BC notaries and lawyers recommend it as a standard part of the closing package.</p>

                    <h3>Moving and Setup Costs</h3>
                    <p>Budget $1,000–$5,000 for a local Metro Vancouver move, depending on volume of possessions and distance. If moving from out of province, costs will be substantially higher. Factor in utility setup deposits, new furniture, and any immediate repairs or upgrades to the new home.</p>

                    <div class="bg-callout">
                        <div class="bg-callout-label">Budget Guideline</div>
                        <p>As a general rule, budget 2% to 4% of the purchase price for total closing costs (excluding the down payment). On an $800,000 purchase, that is $16,000 to $32,000 in addition to your down payment. Your mortgage broker, notary, and buyer's agent should all be able to provide personalized estimates once you have a specific property in mind.</p>
                    </div>

