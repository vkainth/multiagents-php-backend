                <div id="choose-agent" class="bg-section">
                    <h2>1. How to Choose a Buyer's Agent in BC</h2>
                    <p>Your buyer's agent is your advocate throughout one of the largest financial transactions of your life. In BC, buyer's agent commissions are paid by the seller — meaning you receive professional representation at no direct cost. Choosing the right agent is therefore about capability, not cost.</p>

                    <h3>What a Strong Buyer's Agent Does For You</h3>
                    <p>A skilled buyer's agent goes well beyond searching MLS. They help you understand the market, identify fairly priced properties, negotiate effectively, manage the subject removal process, and coordinate with your lender, inspector, and notary or lawyer. In a competitive market, having an experienced negotiator on your side can mean the difference between winning the right home at a fair price and being outbid repeatedly.</p>

                    <h3>Local Market Knowledge</h3>
                    <p>Real estate in BC is intensely local. Pricing, inventory levels, and buyer competition vary significantly between Vancouver, Burnaby, Richmond, North Vancouver, Surrey, and outer Metro areas. An agent who genuinely understands your target area — its micro-market trends, building quality, upcoming developments, and neighbourhood dynamics — is far more valuable than a generalist operating across too large a territory.</p>

                    <h3>Access and Responsiveness</h3>
                    <p>In active markets, listings move quickly. Your agent must be responsive — able to schedule showings within hours, alert you to new listings before they receive multiple offers, and act quickly when you are ready to move. Ask any agent you interview: "How quickly do you typically respond to inquiries, and how do you alert me when a property matching my criteria is listed?"</p>

                    <h3>Questions to Ask Every Buyer's Agent</h3>
                    <ul>
                        <li>How many buyers are you currently representing, and how many transactions have you completed in my target area in the past 12 months?</li>
                        <li>What is your process when we find a home I want to offer on? How quickly can you prepare and submit an offer?</li>
                        <li>Have you ever worked with competing offers? What is your strategy for winning in a multi-offer situation?</li>
                        <li>Who reviews the strata documents on my behalf, and how do you advise me on what to watch for?</li>
                        <li>What inspectors, mortgage brokers, and notaries do you recommend, and can I choose my own?</li>
                        <li>How are you compensated, and does that compensation vary depending on which property I buy?</li>
                    </ul>

                    <div class="bg-callout">
                        <div class="bg-callout-label">Buyer's Tip</div>
                        <p>Be cautious of "dual agency" — when the same agent represents both the buyer and the seller. While dual agency is legal in BC with informed written consent, the agent cannot fully advocate for either party. If the listing agent offers to represent you as well, consider whether you would prefer independent representation.</p>
